"""Recompute report statistics from committed training curves and evaluation summaries.

No training or model downloads. Linear areas are recovered from per-step averages
(six significant digits); nonlinear per-window statistics are not reconstructed.
"""

import csv
import hashlib
import json
import math
import subprocess
import sys
from pathlib import Path

import numpy as np
from scipy.stats import rankdata, spearmanr

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
EXPERIMENTS = ROOT / "experiments" / "episynth"
DATA = HERE / "data"
DATA.mkdir(exist_ok=True)
GENS = ["kernelsynth", "ets", "waveform", "sde", "stepfunction", "tsi", "arima", "fbm", "garch", "chaotic", "timesynth"]
METRICS = {"crps": "scaled_crps", "mase": "MASE[0.5]", "mwsql": "mean_weighted_sum_quantile_loss"}
SOURCES = set()


def read_json(path):
    SOURCES.add(path)
    return json.loads(path.read_text(encoding="utf-8"))


def read_csv(path):
    SOURCES.add(path)
    with path.open(encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def write_csv(name, rows):
    with (DATA / name).open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def write_results_table(rows):
    """Keep the report's displayed results tied to the recomputed run records."""
    labels = ["KernelSynth", "ETS", "Waveform", "SDE", "StepFunction", "TSI",
              "ARIMA", "fBm", "GARCH", "Chaotic", "TimeSynth"]
    primary = {(r["series"], r["generator"]): r for r in rows if r["init_seed"] == 0}
    best = {s: min(primary[s, g]["crps_geo"] for g in GENS) for s in (1, 2)}

    def crps(record):
        value = f"{record['crps_geo']:.3f}"
        return r"\textbf{" + value + "}" if record["crps_geo"] == best[record["series"]] else value

    lines = [
        "% Generated by analyze_runs.py; values come from run_statistics.csv.",
        r"\begin{tabular}{@{}lrrrrr@{}}", r"\toprule",
        r" & \multicolumn{2}{c}{Series 1: 2M} & \multicolumn{3}{c}{Series 2: 40M}\\",
        r"\cmidrule(lr){2-3}\cmidrule(l){4-6}",
        r"Prior & $A$ & CRPS & $A$ & CRPS & MASE\\", r"\midrule",
    ]
    for gen, label in zip(GENS, labels, strict=True):
        first, second = primary[1, gen], primary[2, gen]
        cells = [label, f"{first['area_ema_mnats']:.1f}", crps(first),
                 f"{second['area_ema_mnats']:.1f}", crps(second), f"{second['mase_geo']:.3f}"]
        lines.append(" & ".join(cells) + r" \\")
    repeat = next(r for r in rows if r["run"] == "s2_waveform_seed1")
    lines.extend([r"\midrule", " & ".join([
        "Waveform, seed 1", "---", "---", f"{repeat['area_ema_mnats']:.1f}",
        f"{repeat['crps_geo']:.3f}", f"{repeat['mase_geo']:.3f}",
    ]) + r" \\"])
    lines.extend([r"\bottomrule", r"\end{tabular}"])
    (DATA / "results_table.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def bootstrap_rho(x, y, n_boot=10000, seed=0):
    """Vectorized paired percentile bootstrap, resampling generator families."""
    x, y = np.asarray(x, dtype=float), np.asarray(y, dtype=float)
    rng = np.random.default_rng(seed)
    ix = rng.integers(0, len(x), size=(n_boot, len(x)))
    rx, ry = rankdata(x[ix], axis=1), rankdata(y[ix], axis=1)
    rx -= rx.mean(axis=1, keepdims=True)
    ry -= ry.mean(axis=1, keepdims=True)
    den = np.sqrt((rx**2).sum(1) * (ry**2).sum(1))
    ok = den > 0
    boots = (rx[ok] * ry[ok]).sum(1) / den[ok]
    lo, hi = np.quantile(boots, [0.025, 0.975])
    return {"rho": float(spearmanr(x, y).statistic), "lo": float(lo), "hi": float(hi), "n": len(x)}


def load_run(series, run):
    directory = EXPERIMENTS / f"series{series}_2026-10-19"
    source = directory / "runs" / run
    cfg = read_json(source / "config.json")
    full = read_json(source / "run.json")
    curve = read_csv(source / "train_curve.csv")
    held_path = source / "heldout.jsonl"
    SOURCES.add(held_path)
    held = [json.loads(line) for line in held_path.read_text(encoding="utf-8").splitlines()]
    b, h, n = cfg["train"]["batch_size"], cfg["spec"]["horizon"], cfg["train"]["n_windows"]
    steps = np.array([int(row["step"]) for row in curve])
    seen = np.array([int(row["windows_seen"]) for row in curve])
    losses = np.array([float(row["nats_per_point"]) for row in curve])
    assert np.array_equal(steps, np.arange(1, len(curve) + 1)), run
    assert np.array_equal(seen, steps * b) and len(curve) * b == n, run
    assert np.isfinite(losses).all(), run
    assert sorted(r["fraction"] for r in held) == list(cfg["train"]["checkpoint_fractions"]), run
    final = next(r for r in held if r["fraction"] == 1)
    total = float(losses.sum() * b * h)
    rounding = 0.5 * 10.0 ** (np.floor(np.log10(np.maximum(abs(losses), 1e-300))) - 5)
    bound = float(rounding.sum() * b * h)
    ema = final["ema"]["nats_per_window"]
    raw = final["raw"]["nats_per_window"]
    # Exact within-step ordering is unavailable; first-1% boundary differs by at most one batch.
    start = float(losses[:max(1, len(losses) // 100)].mean())
    rec = {
        "series": series, "run": run, "generator": cfg["generator"], "init_seed": cfg["train"]["init_seed"],
        "n_windows": n, "steps": len(curve), "area_ema_mnats": (total - n * ema) / 1e6,
        "area_raw_mnats": (total - n * raw) / 1e6, "area_ema_mbits": (total - n * ema) / math.log(2) / 1e6,
        "sum_loss_mnats": total / 1e6, "area_export_error_bound_nats": bound,
        "final_ema_nats_per_point": ema / h, "final_raw_nats_per_point": raw / h,
        "initial_first_percent_nats_per_point": start, "loss_drop": start - ema / h,
        "raw_minus_ema_floor_nats_per_point": (raw - ema) / h,
    }
    naive = {r["config"]: r for r in read_csv(directory / "eval" / "seasonal_naive" / "summary.csv")}
    scores = {r["config"]: r for r in read_csv(directory / "eval" / run / "summary.csv")}
    assert len(scores) == len(naive) == 55 and set(scores) == set(naive), run
    tasks = []
    for config in sorted(scores):
        row = {"series": series, "run": run, "generator": cfg["generator"], "config": config}
        assert float(scores[config]["n_windows"]) == float(naive[config]["n_windows"])
        assert float(scores[config]["n_points"]) == float(naive[config]["n_points"])
        for name, metric in METRICS.items():
            base = float(naive[config][metric])
            val = float(scores[config][metric])
            assert np.isfinite([base, val]).all() and base > 0 and val > 0
            row[name + "_ratio"] = val / base
        tasks.append(row)
    for name in METRICS:
        values = np.array([r[name + "_ratio"] for r in tasks])
        rec[name + "_geo"] = float(np.exp(np.log(values).mean()))
        rec[name + "_median"] = float(np.median(values))
        rec[name + "_wins"] = int((values < 1).sum())
        worst = tasks[int(np.argmax(values))]
        rec[name + "_worst_config"] = worst["config"]
        rec[name + "_worst_ratio"] = float(values.max())
    prefixes = []
    cum = np.cumsum(losses) * b * h
    for record in held:
        k = record["step"]
        lf = record["ema"]["nats_per_window"]
        prefixes.append({
            "series": series, "run": run, "generator": cfg["generator"],
            "fraction": record["fraction"], "n_windows": k * b,
            "area_mnats": float(cum[k - 1] - k * b * lf) / 1e6,
            "final_loss_nats_per_point": lf / h, "loss_drop": start - lf / h,
        })
    return rec, tasks, prefixes, {"config": cfg, "run": full}


def main():
    rows, tasks, prefixes, configs = [], [], [], {}
    for series, prefix in [(1, "series_"), (2, "s2_")]:
        for gen in GENS + (["waveform_seed1"] if series == 2 else []):
            rec, task, checkpoints, cfg = load_run(series, prefix + gen)
            rows.append(rec)
            tasks.extend(task)
            prefixes.extend(checkpoints)
            configs[rec["run"]] = cfg
    # Quality ranks use the eleven seed-zero models within each budget series.
    for series in [1, 2]:
        keep = [r for r in rows if r["series"] == series and r["init_seed"] == 0]
        for name in METRICS:
            values = np.array([[next(t[name + "_ratio"] for t in tasks if t["run"] == r["run"] and t["config"] == c)
                                for r in keep] for c in sorted({t["config"] for t in tasks})])
            ranks = rankdata(values, axis=1).mean(0)
            for rec, rank in zip(keep, ranks, strict=True):
                rec[name + "_mean_rank"] = float(rank)
    for name in METRICS:
        rows[-1][name + "_mean_rank"] = ""  # Seed repeat is not a twelfth generator family.

    correlations = []
    subsets = {
        "all_11": set(), "without_chaotic_stepfunction": {"chaotic", "stepfunction"},
        "without_chaotic_waveform_stepfunction": {"chaotic", "waveform", "stepfunction"},
    }
    for series in [1, 2]:
        for subset, excluded in subsets.items():
            keep = [r for r in rows if r["series"] == series and r["init_seed"] == 0 and r["generator"] not in excluded]
            for pred in ["area_ema_mnats", "area_raw_mnats", "final_ema_nats_per_point", "loss_drop"]:
                for target in ["crps_geo", "crps_median", "crps_mean_rank", "mase_geo", "mwsql_geo"]:
                    stat = bootstrap_rho([r[pred] for r in keep], [r[target] for r in keep])
                    correlations.append({"series": series, "subset": subset, "predictor": pred, "target": target, **stat})
    # A separate replacement analysis keeps all families, using seed 1 for Waveform.
    keep = [r for r in rows if r["series"] == 2 and (r["generator"] != "waveform" or r["init_seed"] == 1)]
    for pred in ["area_ema_mnats", "area_raw_mnats", "final_ema_nats_per_point"]:
        stat = bootstrap_rho([r[pred] for r in keep], [r["crps_geo"] for r in keep])
        correlations.append({"series": 2, "subset": "all_11_waveform_seed1", "predictor": pred, "target": "crps_geo", **stat})

    prefix_correlations = []
    for series in [1, 2]:
        for frac in sorted({p["fraction"] for p in prefixes}):
            keep = [p for p in prefixes if p["series"] == series and p["fraction"] == frac and "seed1" not in p["run"]]
            for pred in ["area_mnats", "final_loss_nats_per_point", "loss_drop"]:
                for metric in ["crps_geo", "mase_geo"]:
                    target = [next(r[metric] for r in rows if r["run"] == p["run"]) for p in keep]
                    prefix_correlations.append({
                        "series": series, "fraction": frac, "n_windows": keep[0]["n_windows"],
                        "predictor": pred, "target": metric,
                        "rho": float(spearmanr([p[pred] for p in keep], target).statistic),
                    })

    # Verify saved point baselines against the committed original leaderboard CSV.
    ref = {r["dataset"]: r for r in read_csv(EXPERIMENTS / "reference/gift_eval_leaderboard/gift_eval_seasonal_naive.csv")}
    baseline_check = {}
    for metric in ["MASE[0.5]", "sMAPE[0.5]", "ND[0.5]", "MAE[0.5]", "MSE[0.5]"]:
        diffs = []
        for r in read_csv(EXPERIMENTS / "series2_2026-10-19/eval/seasonal_naive/summary.csv"):
            base = float(ref[r["config"]]["eval_metrics/" + metric])
            diffs.append(abs(float(r[metric]) - base) / max(abs(base), 1e-12))
        baseline_check[metric] = float(max(diffs))

    # Check the linear CSV-derived areas against the author's independently uploaded
    # per-window analysis (displayed to one decimal million nats).
    area_checks = []
    for series in [1, 2]:
        path = EXPERIMENTS / f"series{series}_2026-10-19/analysis/epiplexity_variants.md"
        SOURCES.add(path)
        text = path.read_text(encoding="utf-8")
        for gen in GENS:
            line = next(line for line in text.splitlines() if line.startswith("| " + gen + " |"))
            archived = float(line.split("|")[2].strip())
            own = next(r["area_ema_mnats"] for r in rows if r["series"] == series and r["generator"] == gen and r["init_seed"] == 0)
            assert abs(archived - own) < 0.051, (series, gen, archived, own)
            area_checks.append({"series": series, "generator": gen, "archived_mnats": archived, "recomputed_mnats": own})

    compression = read_json(EXPERIMENTS / "series1_2026-10-19/gzip_baseline.json")
    gzip_correlations = []
    for series in [1, 2]:
        keep = [r for r in rows if r["series"] == series and r["init_seed"] == 0 and r["generator"] in compression]
        stat = bootstrap_rho([compression[r["generator"]]["q16_bytes_per_point"] for r in keep], [r["crps_geo"] for r in keep])
        gzip_correlations.append({"series": series, **stat})

    write_csv("run_statistics.csv", rows)
    write_results_table(rows)
    write_csv("task_ratios.csv", tasks)
    write_csv("correlations.csv", correlations)
    write_csv("checkpoint_statistics.csv", prefixes)
    write_csv("prefix_correlations.csv", prefix_correlations)
    git = ["git", "-c", "safe.directory=" + ROOT.as_posix()]
    commit = subprocess.check_output(git + ["rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
    verification = {
        "source_commit": commit, "run_count": len(rows), "primary_runs": 22, "waveform_repeats": 1,
        "total_training_windows": sum(r["n_windows"] for r in rows),
        "configs_per_run": 55, "export_precision": "six significant digits per step",
        "max_area_rounding_bound_nats": max(r["area_export_error_bound_nats"] for r in rows),
        "archived_area_comparisons": area_checks, "point_baseline_max_relative_difference": baseline_check,
        "bootstrap": {"unit": "generator family", "replicates": 10000, "seed": 0, "interval": "95% percentile"},
        "gzip_q16_crps_correlations": gzip_correlations,
        "per_window_loss_vectors_used": False, "heldout_standard_errors_available": False,
        "files": [{"path": p.relative_to(ROOT).as_posix(), "sha256": hashlib.sha256(p.read_bytes()).hexdigest()} for p in sorted(SOURCES)],
    }
    (DATA / "analysis_verification.json").write_text(json.dumps(verification, indent=2), encoding="utf-8")
    print("series generator   area(Mnat)    floor/pt CRPSgeo  MASEgeo CRPSmedian wins")
    for r in rows:
        print(f"{r['series']:>2} {r['run']:22} {r['area_ema_mnats']:9.3f} {r['final_ema_nats_per_point']:9.4f} {r['crps_geo']:7.3f} {r['mase_geo']:7.3f} {r['crps_median']:7.3f} {r['crps_wins']:2d}")
    print("ALL-GENERATOR CORRELATIONS")
    for r in correlations:
        if r["subset"] in ["all_11", "all_11_waveform_seed1"] and r["target"] == "crps_geo":
            print(r)
    print("BASELINE MAX RELATIVE ERRORS", baseline_check)
    print("ROUNDING BOUND", verification["max_area_rounding_bound_nats"])
    print("GZIP", gzip_correlations)


if __name__ == "__main__":
    main()
